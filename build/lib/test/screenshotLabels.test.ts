import assert from 'assert';
import { spawnSync } from 'child_process';
import { copyFileSync, mkdirSync, mkdtempSync, rmSync, writeFileSync } from 'fs';
import { tmpdir } from 'os';
import { join } from 'path';
import { after, before, suite, test } from 'node:test';

suite('Screenshot label filtering', () => {
	let directory: string;

	before(() => {
		directory = mkdtempSync(join(tmpdir(), 'vscode-screenshot-labels-'));
		mkdirSync(join(directory, 'build/lib'), { recursive: true });
		for (const script of ['screenshotBlocksCi.ts', 'screenshotDiffReport.ts', 'screenshotComment.ts']) {
			copyFileSync(new URL(`../${script}`, import.meta.url), join(directory, 'build/lib', script));
		}
	});

	after(() => rmSync(directory, { recursive: true, force: true }));

	function writeManifest(name: string, fixtures: object[]): string {
		const path = join(directory, name);
		writeFileSync(path, JSON.stringify({ fixtures }));
		return path;
	}

	test('blocks-ci baselines require both screenshot and blocks-ci labels', () => {
		const manifest = writeManifest('blocking.json', [
			{ fixtureId: 'included', imageHash: 'light', labels: ['screenshot', 'blocks-ci'] },
			{ fixtureId: 'dark', imageHash: 'dark', labels: ['blocks-ci'] },
			{ fixtureId: 'animated', imageHash: 'animated', labels: ['animated', 'blocks-ci'] },
			{ fixtureId: 'flaky', imageHash: 'flaky', labels: ['flaky', 'blocks-ci'] },
			{ fixtureId: 'non-blocking', imageHash: 'other', labels: ['screenshot'] },
		]);
		const baseline = join(directory, 'baseline.md');
		writeFileSync(baseline, [
			'<!-- auto-generated by CI — do not edit manually -->',
			'',
			'#### included',
			'![screenshot](https://example.com/images/light)',
			'',
		].join('\n'));
		const result = spawnSync(process.execPath, [
			join(directory, 'build/lib/screenshotBlocksCi.ts'), manifest, baseline, 'https://example.com',
		], { encoding: 'utf8' });

		assert.deepStrictEqual({ status: result.status, stdout: result.stdout, stderr: result.stderr }, {
			status: 0, stdout: '', stderr: '',
		});
	});

	test('reports only screenshot-labeled changes and skips excluded pixel comparisons', () => {
		const local = writeManifest('local.json', [
			{ fixtureId: 'included-added', imageHash: 'added', imagePath: 'added.png', labels: ['screenshot'] },
			{ fixtureId: 'included-error', hasError: true, labels: ['screenshot'] },
			{ fixtureId: 'excluded-added', imageHash: 'added', imagePath: 'added.png' },
			{ fixtureId: 'excluded-error', hasError: true, labels: ['animated'] },
			{ fixtureId: 'excluded-changed', imageHash: 'after', imagePath: 'missing.png', labels: ['flaky'] },
		]);
		const base = writeManifest('base.json', [
			{ fixtureId: 'included-removed', imageHash: 'removed', labels: ['screenshot'] },
			{ fixtureId: 'excluded-removed', imageHash: 'removed', labels: ['animated'] },
			{ fixtureId: 'excluded-changed', imageHash: 'before', labels: ['flaky'] },
		]);
		const result = spawnSync(process.execPath, [
			join(directory, 'build/lib/screenshotDiffReport.ts'), 'https://example.invalid', 'base', 'current', base, local,
		], { encoding: 'utf8', timeout: 10000 });

		assert.deepStrictEqual({
			status: result.status,
			added: result.stdout.includes('included-added'),
			removed: result.stdout.includes('included-removed'),
			errored: result.stdout.includes('included-error'),
			excluded: result.stdout.includes('excluded-'),
			excludedPixelComparison: result.stderr.includes('excluded-changed'),
		}, {
			status: 0, added: true, removed: true, errored: true, excluded: false, excludedPixelComparison: false,
		});
	});
});
