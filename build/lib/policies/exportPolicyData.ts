import { execFileSync, execSync, spawn } from 'child_process';
import { mkdirSync, mkdtempSync, readFileSync, renameSync, rmSync, writeFileSync } from 'fs';
import { tmpdir } from 'os';
import { dirname, join, resolve } from 'path';
import { parseArgs } from 'util';
import { parse, type ParseError } from 'jsonc-parser';
import type { ExportedPolicyDataDto } from './policyDto.ts';
import { mergePolicyData } from './policyDataMerge.ts';

const rootPath = resolve(import.meta.dirname, '..', '..', '..');

// VS Code OAuth app client ID (same as the GitHub Authentication extension)
const CLIENT_ID = '01ab8ac9400c4e429b23';
const DEFAULT_POLICY_EXPORT_PATH = 'build/lib/policies/policyData.jsonc';
const DISCLAIMER = '/** THIS FILE IS AUTOMATICALLY GENERATED USING `npm run export-policy-data`. DO NOT MODIFY IT MANUALLY. **/';

/**
 * Acquires a GitHub token via the OAuth device flow.
 * Opens the browser for the user to authorize, then polls for the token.
 */
async function acquireTokenViaDeviceFlow(): Promise<string> {
	const response1 = await (await fetch('https://github.com/login/device/code', {
		method: 'POST',
		body: JSON.stringify({ client_id: CLIENT_ID, scope: 'repo' }),
		headers: { 'Accept': 'application/json', 'Content-Type': 'application/json' },
	})).json() as { user_code: string; device_code: string; verification_uri: string; expires_in: number; interval: number };

	console.log(`\n  Copy this code: ${response1.user_code}`);
	console.log(`  Then open: ${response1.verification_uri}`);
	console.log(`  Waiting for authorization (up to ${response1.expires_in}s)...\n`);

	let expiresIn = response1.expires_in;
	while (expiresIn > 0) {
		await new Promise(resolve => setTimeout(resolve, 1000 * response1.interval));
		expiresIn -= response1.interval;

		const response2 = await (await fetch('https://github.com/login/oauth/access_token', {
			method: 'POST',
			body: JSON.stringify({
				client_id: CLIENT_ID,
				device_code: response1.device_code,
				grant_type: 'urn:ietf:params:oauth:grant-type:device_code',
			}),
			headers: { 'Accept': 'application/json', 'Content-Type': 'application/json' },
		})).json() as { access_token?: string };

		if (response2.access_token) {
			return response2.access_token;
		}
	}

	throw new Error('Timed out waiting for GitHub authorization');
}

function readPolicyData(path: string): ExportedPolicyDataDto {
	const errors: ParseError[] = [];
	const result = parse(readFileSync(path, 'utf8'), errors) as ExportedPolicyDataDto | undefined;
	if (!result || errors.length > 0) {
		throw new Error(`Failed to parse exported policy data '${path}': ${JSON.stringify(errors)}`);
	}
	return result;
}

function runPolicyExport(codeScript: string, outputPath: string, userDataPath: string, extensionsPath: string, agents: boolean): Promise<void> {
	const args = [
		`--export-policy-data=${outputPath}`,
		`--user-data-dir=${userDataPath}`,
		`--extensions-dir=${extensionsPath}`,
	];
	if (agents) {
		args.unshift('--agents');
	}

	const env = { ...process.env };
	delete env['VSCODE_PORTABLE'];
	delete env['VSCODE_APPDATA'];
	return new Promise((resolve, reject) => {
		const child = spawn(codeScript, args, {
			cwd: rootPath,
			stdio: 'inherit',
			env,
			shell: process.platform === 'win32',
		});
		child.once('error', reject);
		child.once('exit', (code, signal) => {
			if (code === 0) {
				resolve();
			} else {
				reject(new Error(`Policy export process exited with ${signal ? `signal ${signal}` : `code ${code}`}.`));
			}
		});
	});
}

function serializePolicyData(policyData: ExportedPolicyDataDto): string {
	return `${DISCLAIMER}\n${JSON.stringify(policyData, null, 4)}\n`;
}

function writePolicyData(path: string, content: string): void {
	mkdirSync(dirname(path), { recursive: true });
	const temporaryPath = `${path}.${process.pid}.tmp`;
	writeFileSync(temporaryPath, content);
	renameSync(temporaryPath, path);
}

async function main(): Promise<void> {
	const { values } = parseArgs({
		options: {
			check: { type: 'boolean', default: false },
			'skip-transpile': { type: 'boolean', default: false },
		},
	});
	const policyDataPath = resolve(rootPath, DEFAULT_POLICY_EXPORT_PATH);

	if (!values['skip-transpile']) {
		console.log('Transpiling client sources...');
		execSync('npm run transpile-client', { cwd: rootPath, stdio: 'inherit' });
	}

	if (!process.env['GITHUB_TOKEN'] && !process.env['DISTRO_PRODUCT_JSON']) {
		let token: string | undefined;
		try {
			token = execFileSync('gh', ['auth', 'token'], { encoding: 'utf8' }).trim();
			console.log('Set GITHUB_TOKEN from gh CLI.');
		} catch {
			console.log('gh CLI not available, starting GitHub OAuth device flow...');
			token = await acquireTokenViaDeviceFlow();
			console.log('GitHub authorization successful.');
		}
		process.env['GITHUB_TOKEN'] = token;
	}

	const codeScript = process.platform === 'win32'
		? resolve(rootPath, 'scripts', 'code.bat')
		: resolve(rootPath, 'scripts', 'code.sh');
	const temporaryRoot = mkdtempSync(join(tmpdir(), 'vp-'));

	try {
		const workbenchPath = join(temporaryRoot, 'w.jsonc');
		const agentsPath = join(temporaryRoot, 'a.jsonc');

		console.log('Exporting policy data from the Workbench...');
		console.log('Exporting policy data from the Agents window...');
		const exportResults = await Promise.allSettled([
			runPolicyExport(codeScript, workbenchPath, join(temporaryRoot, 'wu'), join(temporaryRoot, 'we'), false),
			runPolicyExport(codeScript, agentsPath, join(temporaryRoot, 'au'), join(temporaryRoot, 'ae'), true),
		]);
		const exportErrors = exportResults
			.filter((result): result is PromiseRejectedResult => result.status === 'rejected')
			.map(result => result.reason);
		if (exportErrors.length > 0) {
			throw new AggregateError(exportErrors, 'Failed to export policy data.');
		}

		const mergedContent = serializePolicyData(mergePolicyData([
			{ source: 'Workbench', data: readPolicyData(workbenchPath) },
			{ source: 'Agents window', data: readPolicyData(agentsPath) },
		]));

		if (values.check) {
			const checkedInContent = readFileSync(policyDataPath, 'utf8');
			if (checkedInContent !== mergedContent) {
				throw new Error('build/lib/policies/policyData.jsonc is out of date. Run `npm run export-policy-data` and include the generated changes.');
			}
			console.log('\nPolicy data is synchronized.');
		} else {
			writePolicyData(policyDataPath, mergedContent);
			console.log(`\nPolicy data exported to ${DEFAULT_POLICY_EXPORT_PATH}`);
		}
	} finally {
		rmSync(temporaryRoot, { recursive: true, force: true });
	}
}

await main();
