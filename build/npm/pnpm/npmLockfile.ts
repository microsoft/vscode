/**
 * An entry of the `packages` section of an npm `package-lock.json` (lockfile version 2 or 3).
 */
export interface NpmLockfileEntry {
	readonly name?: string;
	readonly version?: string;
	readonly resolved?: string;
	readonly integrity?: string;
	readonly link?: boolean;
	readonly dev?: boolean;
	readonly optional?: boolean;
	readonly devOptional?: boolean;
	readonly peer?: boolean;
	readonly extraneous?: boolean;
	readonly hasInstallScript?: boolean;
	readonly dependencies?: Record<string, string>;
	readonly optionalDependencies?: Record<string, string>;
	readonly devDependencies?: Record<string, string>;
	readonly peerDependencies?: Record<string, string>;
}

/**
 * The parts of an npm `package-lock.json` that the conversion reads.
 */
export interface NpmLockfile {
	readonly lockfileVersion: number;
	readonly packages: Record<string, NpmLockfileEntry>;
}

/**
 * A package installed by an npm lockfile.
 */
export interface NpmInstalledPackage {
	/** The `packages` key, for example `node_modules/a/node_modules/b`. */
	readonly key: string;
	/** The name under which the package is installed (the alias name for npm aliases). */
	readonly alias: string;
	/** The real package name. */
	readonly name: string;
	readonly version: string;
	readonly entry: NpmLockfileEntry;
}

export function parseNpmLockfile(content: string): NpmLockfile {
	const lockfile = JSON.parse(content) as NpmLockfile;
	if (!lockfile.packages || lockfile.lockfileVersion < 2) {
		throw new Error(`Unsupported npm lockfile version: ${lockfile.lockfileVersion}. Only lockfile versions 2 and 3 are supported.`);
	}
	return lockfile;
}

function getInstallName(key: string): string {
	return key.substring(key.lastIndexOf('node_modules/') + 'node_modules/'.length);
}

/**
 * Returns every package that the lockfile installs into a `node_modules` folder, in lockfile order.
 * Links (workspace and `file:` folders) are not included. The real name of aliased packages
 * comes from the entry's `name` field, not from its path.
 */
export function getInstalledPackages(lockfile: NpmLockfile): NpmInstalledPackage[] {
	const result: NpmInstalledPackage[] = [];
	for (const [key, entry] of Object.entries(lockfile.packages)) {
		if (!key.includes('node_modules/') || entry.link || !entry.version) {
			continue;
		}
		const alias = getInstallName(key);
		result.push({ key, alias, name: entry.name ?? alias, version: entry.version, entry });
	}
	return result;
}

/**
 * Finds the `packages` key that npm's module resolution uses when the package at `fromKey`
 * (`''` for the project itself) requires `dependencyName`.
 */
export function resolveNpmDependency(lockfile: NpmLockfile, fromKey: string, dependencyName: string): string | undefined {
	let current = fromKey;
	while (true) {
		const candidate = current === '' ? `node_modules/${dependencyName}` : `${current}/node_modules/${dependencyName}`;
		if (lockfile.packages[candidate]) {
			return candidate;
		}
		if (current === '') {
			return undefined;
		}
		const parentIndex = current.lastIndexOf('/node_modules/');
		current = parentIndex === -1 ? '' : current.substring(0, parentIndex);
	}
}

/**
 * Returns the `name@version` keys of every package installed by the lockfile.
 */
export function getUniverseKeys(lockfile: NpmLockfile): Set<string> {
	return new Set(getInstalledPackages(lockfile).map(p => `${p.name}@${p.version}`));
}

/**
 * Renders `name@version` pins as a yarn v1 lockfile. `pnpm import` reads such files (in the
 * workspace root and in members) as preferred versions, keyed by the real package name. npm
 * lockfiles are not used for this because pnpm 11 derives the package name of an npm lockfile
 * entry from its path, which is wrong for npm aliases.
 */
export function renderYarnLockPins(pins: Iterable<string>): string {
	const sorted = [...new Set(pins)].sort();
	const lines = ['# yarn lockfile v1', '# Preferred versions for `pnpm import`, generated by build/npm/pnpm/convert.ts.', ''];
	for (const pin of sorted) {
		const at = pin.lastIndexOf('@');
		if (at <= 0) {
			throw new Error(`Invalid pin: ${pin}`);
		}
		lines.push('', `${JSON.stringify(pin)}:`, `  version ${JSON.stringify(pin.substring(at + 1))}`);
	}
	return lines.join('\n') + '\n';
}

/**
 * Returns whether a dependency specifier is an npm dist-tag (such as `latest` or `next`), possibly
 * behind an npm alias (`npm:pkg@next`). Dist-tags always resolve to the current tag target, so a
 * conversion can't reproduce the version that npm locked from preferred versions alone.
 */
export function isDistTagSpecifier(specifier: string): boolean {
	let spec = specifier.trim();
	if (spec.startsWith('npm:')) {
		const at = spec.indexOf('@', 5);
		spec = at === -1 ? 'latest' : spec.substring(at + 1);
	}
	if (spec === '' || /^(file|link|workspace|git|git\+[a-z]+|github|https?):/.test(spec) || spec.includes('/')) {
		return false;
	}
	return /^[a-z][a-z0-9._-]*$/i.test(spec) && spec.toLowerCase() !== 'x';
}
