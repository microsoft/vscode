import assert from 'assert';
import fs from 'fs';
import path from 'path';
import { suite, test } from 'node:test';
import { getInstalledPackages, getUniverseKeys, isDistTagSpecifier, parseNpmLockfile, renderYarnLockPins, resolveNpmDependency } from '../npmLockfile.ts';

const fixture = path.join(import.meta.dirname, 'fixtures', 'workspace');
const lockfile = parseNpmLockfile(fs.readFileSync(path.join(fixture, 'package-lock.fixture.json'), 'utf8'));

suite('pnpm conversion: npm lockfiles', () => {

	test('installed packages use the real name of npm aliases and skip links', () => {
		assert.deepStrictEqual(getInstalledPackages(lockfile).map(p => `${p.alias} -> ${p.name}@${p.version}`), [
			'a -> a@1.2.0',
			'b -> b@2.1.0',
			'tagged -> tagged@0.0.2-20',
			'tool -> tool@0.1.1',
			'ts -> @scope/ts6@6.0.2',
			'@old/ts -> ts-real@6.0.3',
			'b -> b@2.0.0',
		]);
		assert.deepStrictEqual([...getUniverseKeys(lockfile)].sort(), ['@scope/ts6@6.0.2', 'a@1.2.0', 'b@2.0.0', 'b@2.1.0', 'tagged@0.0.2-20', 'tool@0.1.1', 'ts-real@6.0.3']);
	});

	test('dependencies resolve like node does, from the nearest node_modules', () => {
		assert.deepStrictEqual([
			resolveNpmDependency(lockfile, 'node_modules/ts', 'b'),
			resolveNpmDependency(lockfile, 'node_modules/a', 'b'),
			resolveNpmDependency(lockfile, 'node_modules/ts/node_modules/@old/ts', 'b'),
			resolveNpmDependency(lockfile, '', 'mock'),
			resolveNpmDependency(lockfile, 'node_modules/a', 'missing'),
		], [
			'node_modules/ts/node_modules/b',
			'node_modules/b',
			'node_modules/ts/node_modules/b',
			'node_modules/mock',
			undefined,
		]);
	});

	test('dist-tag specifiers', () => {
		const specifiers = ['latest', 'next', 'npm:rolldown-vite@latest', 'npm:pkg', '^1.0.0', '1.x', 'x', '*', '', 'file:./a', 'github:a/b', 'npm:typescript@^6', '0.0.2-20', '>=1 <2'];
		assert.deepStrictEqual(specifiers.filter(isDistTagSpecifier), ['latest', 'next', 'npm:rolldown-vite@latest', 'npm:pkg']);
	});

	test('yarn lockfile pins are sorted and deduplicated', () => {
		assert.strictEqual(renderYarnLockPins(['b@2.0.0', '@scope/ts6@6.0.2', 'b@2.0.0']), [
			'# yarn lockfile v1',
			'# Preferred versions for `pnpm import`, generated by build/npm/pnpm/convert.ts.',
			'',
			'',
			'"@scope/ts6@6.0.2":',
			'  version "6.0.2"',
			'',
			'"b@2.0.0":',
			'  version "2.0.0"',
			'',
		].join('\n'));
	});
});
