import type { JsonObject, JsonValue } from '../schema.js';
import type { EnvironmentKind, PaginatedResponse, PaginationOptions, RepositoryRef, User } from './missionControl.js';

/** The current task state, derived from its most recent session. */
export type TaskState = 'queued' | 'in_progress' | 'completed' | 'failed' | 'idle' | 'waiting_for_user' | 'timed_out' | 'cancelled';

/** The current state of a session. */
export type SessionState = TaskState;

/** The visibility of a task to its collaborators, repository readers, and listings. */
export type TaskSharingStatus = 'unshared' | 'shared' | 'unlisted';

/** Compute associated with a task. */
export interface TaskCompute {
	/** The compute provider. */
	readonly provider?: 'codespaces' | 'sandboxes';
	/** The identifier of the compute resource. */
	readonly resource_id?: string;
	/** The user or organization login against which compute is provisioned. */
	readonly scope?: string;
}

/** Compute selection supplied when creating a task. */
export interface TaskComputeRequest extends TaskCompute {
	/** The sandbox owner, required for organization-owned app-principal sandbox tasks. */
	readonly user_id?: number;
}

/** The canonical environment binding for a task. */
export interface TaskEnvironment {
	/** The stable identifier of the bound environment. */
	readonly id: string;
	/** The canonical class of compute backing the environment. */
	readonly kind: EnvironmentKind;
}

/** An agent integration that has worked on a task. */
export interface TaskCollaborator {
	/** The type of agent integration, such as a GitHub App. */
	readonly agent_type?: string;
	/** The numeric identifier of the agent integration. */
	readonly agent_id?: number;
	/** The agent's internal task identifier. */
	readonly agent_task_id?: string;
	/** The machine-readable integration slug. */
	readonly slug?: string;
}

/** Custom-agent metadata associated with a task. */
export interface TaskCustomAgent {
	/** The custom agent's filename without its extension. */
	readonly id?: string;
	/** The internal custom-agent identifier. */
	readonly name?: string;
	/** Whether an automation rather than a direct user action initiated the task. */
	readonly is_automation?: boolean;
}

/** A repository reference returned with a task or session. */
export interface Repository {
	/** The unique numeric identifier of the repository. */
	readonly id?: number;
	/** The repository name without its owner. */
	readonly name?: string;
	/** The repository name in owner/name form. */
	readonly full_name?: string;
	/** The account that owns the repository. */
	readonly owner?: User;
}

/** A repository resource created or used by a task, such as an issue or pull request. */
export interface RepositoryResource {
	/** The numeric resource identifier. */
	readonly id: number;
	/** The internal resource type, such as pull_request or issue. */
	readonly type: string;
	/** The GraphQL global identifier of the resource. */
	readonly global_id?: string;
	/** The lifecycle state of the resource. */
	readonly state?: 'open' | 'draft' | 'closed' | 'merged';
}

/** A Git branch reference generated by a task. */
export interface BranchResource {
	/** The head branch name. */
	readonly head_ref: string;
	/** The base branch name. */
	readonly base_ref: string;
}

/** An Azure DevOps resource identified by its canonical URL. */
export interface AzureDevOpsResource {
	/** The canonical Azure DevOps resource URL. */
	readonly url: string;
}

/** A resource generated by a task. */
export interface TaskArtifact {
	/** The provider namespace of the resource. */
	readonly provider: 'github' | 'azure_devops';
	/** The artifact type determining the resource data shape. */
	readonly type: 'pull' | 'branch' | 'github_resource' | 'azure_devops_resource';
	/** The resource data carried by the artifact. */
	readonly data: RepositoryResource | BranchResource | AzureDevOpsResource;
}

/** Display-only Azure DevOps repository context supplied by an authorized caller. */
export interface AzureDevOpsRepositoryContext extends AzureDevOpsResource {
	/** The repository name. */
	readonly name?: string;
	/** The default branch of the repository. */
	readonly default_branch?: string;
}

/** The experiment assignment used when creating a task. */
export interface ExperimentAssignmentResponse {
	/** The stable experiment name. */
	readonly experiment_name: string;
	/** The numeric experiment variant. */
	readonly variant: number;
	/** The stable experiment variant name. */
	readonly variant_name: string;
	/** Opaque assignment context returned by the experiment provider. */
	readonly assignment_context: string;
}

/** Task metadata returned by listings and task lifecycle operations. */
export interface Task {
	/** The unique task identifier. */
	readonly id: string;
	/** The API URL for the task. */
	readonly url?: string;
	/** The web URL for the task. */
	readonly html_url?: string;
	/** The human-readable name derived from the task prompt. */
	readonly name?: string;
	/** The entity that created the task. */
	readonly creator?: User;
	/** The type of the task creator. */
	readonly creator_type?: 'user' | 'organization';
	/** Collaborator references, with numeric IDs retained by the internal legacy representation. */
	readonly user_collaborators?: readonly (User | number)[];
	/** Agent integrations that have worked on the task. */
	readonly agent_collaborators?: readonly TaskCollaborator[];
	/** The account that owns the repository. */
	readonly owner?: User;
	/** The task's primary repository. */
	readonly repository?: Repository;
	/** Ordered associated repositories, all of which a viewer must be able to read. */
	readonly repositories?: readonly Repository[];
	/** The deprecated task status, replaced by state. */
	readonly status?: TaskState;
	/** The current state derived from the most recent session. */
	readonly state: TaskState;
	/** The number of sessions in the task. */
	readonly session_count?: number;
	/** The event type that originated the task. */
	readonly event_type?: string;
	/** Resources generated by the task. */
	readonly artifacts?: readonly TaskArtifact[];
	/** The archive timestamp, or null when the task is not archived. */
	readonly archived_at?: string | null;
	/** The timestamp of the most recent update. */
	readonly updated_at?: string;
	/** The deprecated legacy name for updated_at. */
	readonly last_updated_at?: string;
	/** The timestamp when the task was created. */
	readonly created_at: string;
	/** Whether the latest session supports remote steering through Mission Control. */
	readonly remote_steerable: boolean;
	/** The current environment binding, null or omitted when unavailable. */
	readonly current_environment?: TaskEnvironment | null;
	/** Custom-agent metadata associated with the task. */
	readonly custom_agent?: TaskCustomAgent;
	/** The experiment assignment used while creating the task. */
	readonly experiment_assignment?: ExperimentAssignmentResponse;
	/** The automation that created the task, omitted for non-automation tasks. */
	readonly automation_id?: string;
	/** The exact automation revision used for the run, omitted when not recorded. */
	readonly automation_revision_id?: string;
	/** The deadline after which the session becomes stale without a heartbeat. */
	readonly stale_at?: string;
	/** The compute environment associated with the task. */
	readonly compute?: TaskCompute;
	/** The visibility of the task to readers and collection listings. */
	readonly sharing_status?: TaskSharingStatus;
	/** The Azure DevOps repository against which the task is running. */
	readonly azure_devops_repository_context?: AzureDevOpsRepositoryContext;
}

/** Billing units consumed by a session. */
export interface SessionUsage {
	/** The billing unit, using AI credits for newer sessions and premium requests for older ones. */
	readonly type: 'ai_credits' | 'premium_requests';
	/** Consumed units; AI credits are whole nano units and premium requests may be fractional. */
	readonly amount: number;
	/** The deprecated internal alias for amount. */
	readonly credits?: number;
}

/** Error details for a failed session. */
export interface SessionError {
	/** The session failure message. */
	readonly message?: string;
}

/** Full session details within a task. */
export interface Session {
	/** The unique session identifier. */
	readonly id: string;
	/** The session name. */
	readonly name?: string;
	/** The user who created the session. */
	readonly user?: User;
	/** The account that owns the repository. */
	readonly owner?: User;
	/** The session's primary repository. */
	readonly repository?: Repository;
	/** Ordered repositories inherited from the parent task. */
	readonly repositories?: readonly Repository[];
	/** The numeric agent identifier. */
	readonly agent_id?: number;
	/** The machine-readable agent integration slug. */
	readonly agent_slug?: string;
	/** The agent's internal task identifier. */
	readonly agent_task_id?: string;
	/** The identifier of the task containing the session. */
	readonly task_id?: string;
	/** The current session state. */
	readonly state: SessionState;
	/** The session creation timestamp. */
	readonly created_at: string;
	/** The most recent update timestamp. */
	readonly updated_at?: string;
	/** The deprecated legacy name for updated_at. */
	readonly last_updated_at?: string;
	/** The session completion timestamp. */
	readonly completed_at?: string;
	/** The event type that triggered the session. */
	readonly event_type?: string;
	/** The URL of the triggering event. */
	readonly event_url?: string;
	/** The content of the triggering event. */
	readonly prompt?: string;
	/** The internal representation of the triggering event's content. */
	readonly event_content?: string;
	/** Identifiers used for tracking the triggering event. */
	readonly event_identifiers?: readonly string[];
	/** The type of resource associated with the session. */
	readonly resource_type?: string;
	/** The numeric identifier of the associated resource. */
	readonly resource_id?: number;
	/** The resource number, such as a pull request number. */
	readonly resource_number?: number;
	/** The GraphQL global identifier of the associated resource. */
	readonly resource_global_id?: string;
	/** The state of the associated resource. */
	readonly resource_state?: string;
	/** The head branch name. */
	readonly head_ref?: string;
	/** The base branch name. */
	readonly base_ref?: string;
	/** The associated GitHub Actions workflow run identifier. */
	readonly workflow_run_id?: number;
	/** The model used for the session. */
	readonly model?: string;
	/** The reasoning-effort override, empty when no override applies. */
	readonly reasoning_effort?: string;
	/** The premium request count retained by the internal API. */
	readonly premium_requests?: number;
	/** Structured billing usage for the session. */
	readonly usage?: SessionUsage;
	/** Whether the session supports remote steering through Mission Control. */
	readonly remote_steerable?: boolean;
	/** Error details when the session failed. */
	readonly error?: SessionError;
	/** The deadline after which the session becomes stale without a heartbeat. */
	readonly stale_at?: string;
	/** The immutable environment binding established at session creation. */
	readonly environment_id?: string;
	/** The producer's verbatim AHP resource URI, which cannot be derived from the session ID. */
	readonly ahp_resource_uri?: string;
}

/** A task detail response including its associated sessions. */
export interface GetTaskResponse extends Task {
	/** The sessions associated with the task. */
	readonly sessions?: readonly Session[];
}

/** A selected Copilot Space to load as instructions during sandbox provisioning. */
export interface TaskSpace {
	/** The slug of the selected Space. */
	readonly slug: string;
	/** The owner login of the selected Space. */
	readonly owner: string;
}

/** Parameters for creating a task with optional repository and compute context. */
export interface CreateTaskRequest {
	/** The user's prompt for the agent. */
	readonly prompt: string;
	/** An existing caller-owned online environment, or github-sandbox to provision a managed sandbox. */
	readonly environment_id?: string;
	/** The agent identifier, defaulting to the coding agent. */
	readonly agent_id?: number;
	/** Up to 50 same-owner repositories in primary-first order; omit or use an empty array for repo-less tasks. */
	readonly repositories?: readonly RepositoryRef[];
	/** Additional prompting for the agent. */
	readonly problem_statement?: string;
	/** The user's written prompt in the internal event representation. */
	readonly event_content?: string;
	/** The model identifier, subject to the caller's plan and organization policies. */
	readonly model?: string;
	/** The reasoning-effort override, omitted or empty for no override. */
	readonly reasoning_effort?: string;
	/** The cloud agent permission mode, defaulting to default. */
	readonly permission_mode?: 'default' | 'allow_all';
	/** The managed sandbox principal; app mode is restricted to allowlisted internal integrations. */
	readonly github_principal_mode?: 'unspecified' | 'user' | 'copilot_swe_agent_app';
	/** The custom agent filename without its extension. */
	readonly custom_agent?: string;
	/** Whether to create a pull request; defaults differ between public and internal requests. */
	readonly create_pull_request?: boolean;
	/** The base ref for a new branch or pull request. */
	readonly base_ref?: string;
	/** An existing head ref to commit to instead of creating a new branch. */
	readonly head_ref?: string;
	/** The event type that originated the task. */
	readonly event_type?: string;
	/** The originating mobile product, used only for attribution. */
	readonly integration_slug?: 'copilot-mobile-ios' | 'copilot-mobile-android';
	/** The URL of the triggering event. */
	readonly event_url?: string;
	/** Event identifiers used for tracking. */
	readonly event_identifiers?: readonly string[];
	/** Compute selection, including a required scope for repository-less sandbox provisioning. */
	readonly compute?: TaskComputeRequest;
	/** Caller-authorized Azure DevOps repository context. */
	readonly azure_devops_repository_context?: AzureDevOpsRepositoryContext;
	/** An existing caller-authorized Azure DevOps pull request to record as an artifact. */
	readonly azure_devops_pull_request?: AzureDevOpsResource;
	/** A selected Copilot Space, supported only when provisioning a new compatible sandbox. */
	readonly space?: TaskSpace;
	/** The task visibility at creation, defaulting to unshared. */
	readonly sharing_status?: TaskSharingStatus;
}

