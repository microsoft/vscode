/** Task filters shared by the general task list and automation run history. */
export interface TaskListOptions extends PaginationOptions {
	/** The field to sort by, defaulting to updated_at. */
	readonly sort?: 'updated_at' | 'created_at';
	/** The sort direction, defaulting to descending. */
	readonly direction?: 'asc' | 'desc';
	/** Comma-separated task states to include. */
	readonly state?: string;
	/** Whether to return archived tasks instead of non-archived tasks, defaulting to false. */
	readonly is_archived?: boolean;
	/** Whether to include aggregate active, archived, and waiting-for-user counts. */
	readonly include_counts?: boolean;
}

/** Additional query filters for the authenticated user's task list. */
export interface ListTasksOptions extends TaskListOptions {
	/** Include tasks updated at or after this ISO 8601 timestamp. */
	readonly since?: string;
	/** Filter by artifact type. */
	readonly artifact_type?: 'pull';
	/** Filter by the numeric identifier of an artifact. */
	readonly artifact_id?: number;
	/** Artifact states to match, requiring artifact_type and combined with task state using OR. */
	readonly artifact_state?: readonly ('open' | 'draft' | 'closed' | 'merged')[];
	/** Select review tasks or repository-less persisted sandbox chat tasks. */
	readonly type?: 'review' | 'chat';
	/** Custom-agent names to include, combined with agent IDs using OR. */
	readonly custom_agent_name?: readonly string[];
	/** Explicitly select tasks with or without a repository, including repo-less chat tasks when false. */
	readonly with_repo?: boolean;
	/** Creator user IDs to include. */
	readonly creator_id?: readonly number[];
	/** Comma-separated agent integration IDs to include. */
	readonly include_agent_ids?: string;
	/** Comma-separated environment kinds, combined with agent and custom-agent filters using OR. */
	readonly include_environment_kinds?: string;
	/** Case-insensitive task-name search requiring every whitespace-separated word to match. */
	readonly q?: string;
	/** Comma-separated task identifiers to include. */
	readonly task_ids?: string;
	/** Filter by the numeric repository identifier. */
	readonly repository_id?: number;
}

