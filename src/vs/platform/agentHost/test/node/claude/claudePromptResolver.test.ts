import assert from 'assert';
import { URI } from '../../../../../base/common/uri.js';
import { ensureNoDisposablesAreLeakedInTestSuite } from '../../../../../base/test/common/utils.js';
import { toHostSnapshotAttachmentMeta } from '../../../common/meta/agentSnapshotAttachmentMeta.js';
import { MessageAttachmentKind, type MessageAttachment } from '../../../common/state/protocol/state.js';
import { resolvePromptToContentBlocks } from '../../../node/claude/claudePromptResolver.js';

suite('claudePromptResolver', () => {

	ensureNoDisposablesAreLeakedInTestSuite();

	function referencesText(prompt: string, attachments: MessageAttachment[]): string {
		return resolvePromptToContentBlocks(prompt, attachments)
			.map(block => (block as { text?: string }).text ?? '')
			.join('\n');
	}

	test('a host-created snapshot path is annotated read-only, a normal file reference is not (#331154)', () => {
		const snapshotUri = URI.file('/data/attachments/id/Pasted text #1.txt');
		const snapshot: MessageAttachment = {
			type: MessageAttachmentKind.Resource,
			label: 'Pasted text #1',
			displayKind: 'document',
			uri: snapshotUri.toString(),
			_meta: toHostSnapshotAttachmentMeta('text/plain'),
		} as MessageAttachment;
		const fileUri = URI.file('/workspace/real.txt');
		const normal: MessageAttachment = {
			type: MessageAttachmentKind.Resource,
			label: 'real.txt',
			displayKind: 'document',
			uri: fileUri.toString(),
		} as MessageAttachment;

		const text = referencesText('trim this', [snapshot, normal]);

		assert.ok(text.includes(`- ${snapshotUri.fsPath} (read-only snapshot — do not edit this file)`), `text: ${text}`);
		assert.ok(text.includes(`- ${fileUri.fsPath}`) && !text.includes(`- ${fileUri.fsPath} (read-only`), `text: ${text}`);
	});
});
